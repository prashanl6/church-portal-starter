/**
 * Runs everything: resets the local test database, then both suites, then writes the
 * catalogue of every test case (docs/TEST_CASES.md). Needs the site running locally.
 */
import { spawnSync } from 'child_process';
import { mkdtempSync, readFileSync, writeFileSync, mkdirSync } from 'fs';
import { tmpdir } from 'os';
import { join } from 'path';

const base = process.env.BASE_URL || 'http://localhost:3000';
if (!/localhost|127\.0\.0\.1/.test(base)) { console.error('Refusing to run against a non-local site.'); process.exit(2); }

const run = (args, env = {}) => spawnSync('node', args, { stdio: 'inherit', env: { ...process.env, ...env } });
if (run(['scripts/reset-test-db.js']).status !== 0) process.exit(2);

const dir = mkdtempSync(join(tmpdir(), 'church-tests-'));
const out = [];
let failed = false;
for (const f of ['tests/test-plan.api.mjs', 'tests/full-coverage.api.mjs']) {
  const json = join(dir, f.split('/').pop() + '.json');
  const res = run([f], { RESULTS_JSON: json });
  if (res.status !== 0) failed = true;
  try { out.push(...JSON.parse(readFileSync(json, 'utf8'))); } catch {}
}

const AREAS = {
  SEC: 'Security and login', ROL: 'Role access matrix', PUB: 'Visitor pages', AUT: 'Login and sessions', VAL: 'Bad input',
  FIN: 'Bank account and hall rate', AST: 'Assets', PPL: 'People, birthdays, anniversaries', NTC: 'Notices', SRM: 'Sermons',
  PRC: 'Process documents', FIL: 'File access', BKG: 'Hall bookings', MED: 'Medical equipment', ACC: 'Accounts',
  APR: 'Approvals', AUD: 'Audit log', PRF: 'Speed',
};
const order = Object.keys(AREAS);
out.sort((a, b) => order.indexOf(a.id.slice(0, 3)) - order.indexOf(b.id.slice(0, 3)) || a.id.localeCompare(b.id));
const checks = out.reduce((n, t) => n + t.checks.length, 0);
const passed = out.filter((t) => t.checks.every((c) => c.pass)).length;
let md = `# Test cases and results\n\nGenerated by \`npm test\` (${new Date().toISOString().slice(0, 10)}). Every case below was executed against a freshly reset local copy of the site.\n\n`;
md += `**${passed} of ${out.length} test cases passed (${checks} individual checks).**\n\n`;
md += `Roles: **Visitor** (not logged in) · **Staff** (view only, plus medical loans) · **Administrator A** (makes a change) · **Administrator B** (a different administrator who approves it).\n\n`;
let area = '';
for (const t of out) {
  const a = AREAS[t.id.slice(0, 3)] || t.id.slice(0, 3);
  if (a !== area) { md += `\n## ${a}\n`; area = a; }
  const ok = t.checks.every((c) => c.pass);
  md += `\n### ${t.id}  ${t.title}  ${ok ? '✅' : '❌'}\n`;
  if (t.roles) md += `*Who:* ${t.roles}\n\n`;
  for (const c of t.checks) md += `- ${c.pass ? '✅' : '❌'} ${c.label}${c.pass || !c.extra ? '' : ` — ${c.extra}`}\n`;
}
mkdirSync('docs', { recursive: true });
writeFileSync('docs/TEST_CASES.md', md);
console.log(`\nWrote docs/TEST_CASES.md — ${passed} of ${out.length} cases, ${checks} checks.`);
process.exit(failed ? 1 : 0);
